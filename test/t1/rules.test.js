test('K4.1 문서 전체가 -십시오 체계로 일관되면 경고가 아니라 정보', opts, async () => {
  const r = await lintTextT1('밸브를 닫으십시오.\n전원을 끄십시오.\n플러그를 뽑으십시오.\n문을 닫으십시오.');
  const f = r.findings.filter((x) => x.ruleId === 'K4.1');
  assert.equal(f.length, 4);
  assert.ok(f.every((x) => x.severity === 'info'));
  const mixed = await lintTextT1('밸브를 닫으십시오.\n전원을 끄세요.');
  assert.ok(mixed.findings.some((x) => x.ruleId === 'K4.1' && x.severity === 'warn'));
});

