test('K3.2 피동 밀도: 문서 대부분이 피동이면 정보, 능동이면 없음', opts, async () => {
  assert.ok((await ids(docs.passiveBad)).includes('K3.2'));
  assert.ok(!(await ids(docs.passiveGood)).includes('K3.2'));
  assert.ok(!(await ids('값이 저장된다.')).includes('K3.2'), '문장 5개 미만은 비율을 내지 않는다');
  assert.ok(!(await ids('전원을 켜세요.\n값이 저장됩니다.\n설정을 바꾸세요.\n물을 넣으세요.\n시스템이 값을 읽습니다.\n뚜껑을 여세요.')).includes('K3.2'));
  const f = (await lintTextT1(docs.passiveBad)).findings.find((x) => x.ruleId === 'K3.2');
  assert.equal(f.severity, 'info');
});

