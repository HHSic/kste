test('T1 이 켜지면 T0 근사(K2.1 정규식·명사 연쇄 근사)는 꺼지고 정밀판이 대신한다', opts, async () => {
  const r = await lintTextT1('수신함을 확인함.\n');
  assert.equal(r.meta.t1, true);
  assert.equal(r.meta.tier, 'T0+T1');
  assert.ok(r.findings.some((f) => f.ruleId === 'K2.1-001' && f.tier === 1));
  assert.ok(!r.findings.some((f) => f.ruleId === 'K2.1'));
  const r2 = await lintTextT1('수신함을 확인한다.\n');
  assert.ok(!r2.findings.some((f) => f.base === 'K2.1'));
  const t0 = await lintTextT1('수신함을 확인함.\n', { t1: 'off' });
  assert.equal(t0.meta.t1, false);
  assert.ok(t0.findings.some((f) => f.ruleId === 'K2.1'));
});

